import type { Metadata } from "next";
import { redirect } from "next/navigation";
import { getTranslations } from "next-intl/server";
import { AuthShell } from "@/components/auth-shell";
import { SignOutButton } from "@/components/shell/user-menu";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { getCurrentUser, homeFor, needsMfa } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import { MfaForm } from "./mfa-form";

export const metadata: Metadata = { title: "2FA" };

// Second factor for admins and the finance role. Without a verified TOTP factor it enrols one (QR code);
// otherwise it asks for the current code. Does not call requireUser, which redirects here.
export default async function VerificacionPage() {
  const user = await getCurrentUser();
  if (!user) redirect("/auth/sair?motivo=inativo");
  if (!needsMfa(user.tipo) || user.aal === "aal2") redirect(homeFor(user.tipo));

  const t = await getTranslations("mfa");
  const supabase = await createClient();
  const { data: factors } = await supabase.auth.mfa.listFactors();
  const verified = factors?.all.find((f) => f.factor_type === "totp" && f.status === "verified");

  let enrol: { id: string; qr: string; secret: string } | null = null;
  if (!verified) {
    // Drop half-finished enrolments (e.g. a reloaded page) before creating a new one.
    for (const f of factors?.all ?? []) {
      if (f.factor_type === "totp" && f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
    }
    const { data, error } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: "Brillanza" });
    if (error || !data) {
      console.warn(`[mfa] enroll failed: ${error?.code ?? "unknown"}`);
    } else {
      enrol = { id: data.id, qr: data.totp.qr_code, secret: data.totp.secret };
    }
  }

  return (
    <AuthShell footer={<SignOutButton className="mx-auto" />}>
      <Card>
        <CardHeader>
          <CardTitle className="text-xl">{verified ? t("challengeTitle") : t("enrollTitle")}</CardTitle>
          <CardDescription>{verified ? t("challengeSubtitle") : t("enrollSubtitle")}</CardDescription>
        </CardHeader>
        <CardContent className="flex flex-col gap-4">
          {verified ? (
            <MfaForm factorId={verified.id} />
          ) : enrol ? (
            <>
              <ol className="list-decimal space-y-1 pl-5 text-sm text-muted-foreground">
                <li>{t("step1")}</li>
                <li>{t("step2")}</li>
                <li>{t("step3")}</li>
              </ol>
              {/* SVG data URL generated by Supabase; next/image adds nothing here. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={enrol.qr} alt={t("qrAlt")} width={192} height={192} className="mx-auto rounded-md bg-white p-2" />
              <div className="text-center">
                <p className="text-xs text-muted-foreground">{t("secret")}</p>
                <code className="text-sm break-all select-all">{enrol.secret}</code>
              </div>
              <MfaForm factorId={enrol.id} />
            </>
          ) : (
            <p role="alert" className="rounded-md bg-destructive/10 px-3 py-2 text-sm text-destructive">
              {t("enrollFailed")}
            </p>
          )}
          <p className="text-xs text-muted-foreground">{t("lostDevice")}</p>
        </CardContent>
      </Card>
    </AuthShell>
  );
}
